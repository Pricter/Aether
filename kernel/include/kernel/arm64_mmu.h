#pragma once

/* Four-level AArch64 translation with 4 KiB granules and 48-bit addresses. */
#define ARM64_PAGE_SHIFT 12U
#define ARM64_TABLE_INDEX_BITS 9U
#define ARM64_TABLE_ENTRIES 512UL
#define ARM64_TABLE_INDEX_MASK (ARM64_TABLE_ENTRIES - 1)
#define ARM64_LEVEL_ZERO_SHIFT 39U
#define ARM64_LEVEL_TWO_SHIFT 21U
#define ARM64_LEAF_LEVEL 3U
#define ARM64_DESCRIPTOR_VALID 1UL
#define ARM64_DESCRIPTOR_TABLE_OR_PAGE 3UL
#define ARM64_DESCRIPTOR_ADDRESS 0x0000fffffffff000UL
#define ARM64_PAGE_NORMAL_MEMORY (1UL << 2)
#define ARM64_PAGE_USER_ACCESS (1UL << 6)
#define ARM64_PAGE_READ_ONLY (1UL << 7)
#define ARM64_PAGE_INNER_SHAREABLE (3UL << 8)
#define ARM64_PAGE_ACCESS_FLAG (1UL << 10)
#define ARM64_PAGE_NOT_GLOBAL (1UL << 11)
#define ARM64_PAGE_PRIVILEGED_NO_EXECUTE (1UL << 53)
#define ARM64_PAGE_USER_NO_EXECUTE (1UL << 54)
